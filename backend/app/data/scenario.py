def _zone(**kwargs) -> dict:
    min_lon, min_lat, max_lon, max_lat = kwargs["bounds"]
    kwargs["polygon"] = [
        [min_lon, min_lat],
        [max_lon, min_lat],
        [max_lon, max_lat],
        [min_lon, max_lat],
        [min_lon, min_lat],
    ]
    kwargs["center"] = [(min_lon + max_lon) / 2, (min_lat + max_lat) / 2]
    return kwargs


